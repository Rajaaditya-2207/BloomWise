// Helper functions
export function getCropById(id) {
    return indianCrops.find(c => c.id === id);
}

export function getCropsByCategory(category) {
    return indianCrops.filter(c => c.category === category);
}

export function getCropsBySeason(season) {
    return indianCrops.filter(c => c[season] === true);
}

export function getCropsByClimateZone(zone) {
    return indianCrops.filter(c => c.suitableClimateZones.includes(zone));
}

// Get current Kc based on days after planting
export function getCurrentKc(crop, daysAfterPlanting) {
    if (daysAfterPlanting <= crop.stageInitialDays) {
        return crop.kcInitial;
    } else if (daysAfterPlanting <= crop.stageInitialDays + crop.stageDevDays) {
        // Linear interpolation during development
        const progressInDev = (daysAfterPlanting - crop.stageInitialDays) / crop.stageDevDays;
        return crop.kcInitial + (crop.kcMid - crop.kcInitial) * progressInDev;
    } else if (daysAfterPlanting <= crop.stageInitialDays + crop.stageDevDays + crop.stageMidDays) {
        return crop.kcMid;
    } else {
        // Linear decline during late stage
        const daysInLate = daysAfterPlanting - (crop.stageInitialDays + crop.stageDevDays + crop.stageMidDays);
        const progressInLate = Math.min(daysInLate / crop.stageLateDays, 1);
        return crop.kcMid + (crop.kcEnd - crop.kcMid) * progressInLate;
    }
}

// Get growth stage name
export function getGrowthStage(crop, daysAfterPlanting) {
    if (daysAfterPlanting <= crop.stageInitialDays) {
        return 'initial';
    } else if (daysAfterPlanting <= crop.stageInitialDays + crop.stageDevDays) {
        return 'development';
    } else if (daysAfterPlanting <= crop.stageInitialDays + crop.stageDevDays + crop.stageMidDays) {
        return 'mid';
    } else {
        return 'late';
    }
}

